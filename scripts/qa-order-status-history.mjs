#!/usr/bin/env node
import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {readFileSync} from 'node:fs';
const db=new DatabaseSync(':memory:');
db.exec('PRAGMA foreign_keys=ON');
const schema=readFileSync(new URL('../api/schema.sql',import.meta.url),'utf8');
db.exec(schema);
const insert=db.prepare("INSERT INTO orders(customer_name,device_model,status) VALUES (?,?,?)");
const event=db.prepare("INSERT INTO order_status_history(order_id,previous_status,new_status,origin,actor) VALUES (?,?,?,?,?)");
const read=id=>db.prepare('SELECT previous_status,new_status,origin,actor FROM order_status_history WHERE order_id=? ORDER BY id').all(id);
const old=Number(insert.run('Existing','Model','pendente').lastInsertRowid);
assert.deepEqual(read(old),[],'Do not invent historical events for legacy orders');
db.exec('BEGIN IMMEDIATE');
const id=Number(insert.run('New','Model','pendente').lastInsertRowid);
event.run(id,null,'pendente','admin_creation','admin');
db.exec('COMMIT');
assert.equal(read(id).length,1);
db.exec('BEGIN IMMEDIATE');
db.prepare('UPDATE orders SET status=? WHERE id=?').run('em_processamento',id);
event.run(id,'pendente','em_processamento','admin_status','admin');
db.exec('COMMIT');
assert.deepEqual(read(id).map(x=>x.new_status),['pendente','em_processamento']);
db.exec('BEGIN IMMEDIATE');
db.prepare('UPDATE orders SET status=? WHERE id=?').run('concluido',id);
event.run(id,'em_processamento','concluido','admin_status','admin');
db.exec('ROLLBACK');
assert.equal(db.prepare('SELECT status FROM orders WHERE id=?').get(id).status,'em_processamento');
assert.equal(read(id).length,2,'Rollback must discard event and order change');
assert.throws(()=>event.run(999999,null,'pendente','reseller_api','reseller'),/FOREIGN KEY/);
db.close();
console.log('ORDER_STATUS_HISTORY_PASS: migration, no invented history, transactional writes, rollback and FK');
